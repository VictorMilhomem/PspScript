using PspScript.Ast;
using PspScript.Semantics;

namespace PspScript.CodeGen;

public sealed partial class CCodeGenerator
{
    private readonly ProgramNode _program;
    private readonly SemanticModel _model;
    private readonly SymbolTable _symbols;
    private readonly CSourceWriter _writer = new();
    private int _loopCounter;

    public CCodeGenerator(ProgramNode program, SemanticModel model)
    {
        _program = program;
        _model = model;
        _symbols = model.Symbols;
    }

    public static string Generate(ProgramNode program, SemanticModel model)
    {
        var generator = new CCodeGenerator(program, model);
        return generator.EmitProgram();
    }

    public string EmitProgram()
    {
        EmitHeaderAndIncludes();
        EmitStaticArenas();
        EmitForwardDeclarations();
        EmitStructsAssetsAndGlobals();
        EmitMessageTaggedUnionAndMailbox();
        EmitActorPoolsAndSingletons();
        EmitActorMethodsAndHandlers();
        EmitGameStatesAndTransitions();
        EmitFreeFunctions();
        EmitMainEntryPoint();

        return _writer.ToString();
    }

    // ========================================================================
    // 1. Runtime Header & Standard Includes
    // ========================================================================

    private void EmitHeaderAndIncludes()
    {
        _writer.WriteLine("/*");
        _writer.WriteLine(" * Auto-generated by PSPScript C99 Transpiler.");
        _writer.WriteLine(" * Target: Sony PlayStation Portable (Allegrex MIPS32 / PSPSDK) & SDL2.");
        _writer.WriteLine(" * Memory Model: Static Arenas & Fixed-Capacity Actor Pools (Zero Heap).");
        _writer.WriteLine(" */");
        _writer.WriteLine();
        _writer.WriteLine("#define PSPS_RUNTIME_IMPLEMENTATION");
        _writer.WriteLine("#include \"Runtime/psps_runtime.h\"");
        _writer.WriteLine("#include <stdint.h>");
        _writer.WriteLine("#include <stdbool.h>");
        _writer.WriteLine("#include <string.h>");
        _writer.WriteLine("#include <math.h>");
    }

    // ========================================================================
    // Static Arenas (.bss)
    // ========================================================================

    private void EmitStaticArenas()
    {
        _writer.WriteSectionHeader("Static Memory Arenas (.bss)");

        long ramBudget = _symbols.ConfiguredRamBudgetBytes ?? (16L * 1024L * 1024L);
        long levelArenaBytes = Math.Clamp(ramBudget / 16, 128L * 1024L, 1024L * 1024L);
        long frameArenaBytes = Math.Clamp(ramBudget / 128, 32L * 1024L, 128L * 1024L);

        _writer.WriteLine($"#define PSPS_CONFIG_RAM_BUDGET   ((size_t){ramBudget}u)");
        _writer.WriteLine($"#define PSPS_LEVEL_ARENA_SIZE    ((size_t){levelArenaBytes}u)");
        _writer.WriteLine($"#define PSPS_FRAME_ARENA_SIZE    ((size_t){frameArenaBytes}u)");
        _writer.WriteLine("#define PSPS_MAILBOX_CAPACITY    256u");
        _writer.WriteLine();
        _writer.WriteLine("static uint8_t      g_level_arena_buf[PSPS_LEVEL_ARENA_SIZE] PSPS_ALIGNED(16);");
        _writer.WriteLine("static uint8_t      g_frame_arena_buf[PSPS_FRAME_ARENA_SIZE] PSPS_ALIGNED(16);");
        _writer.WriteLine("static psps_arena_t g_level_arena;");
        _writer.WriteLine("static psps_arena_t g_frame_arena;");
    }

    // ========================================================================
    // 3. Forward Declarations
    // ========================================================================

    private void EmitForwardDeclarations()
    {
        _writer.WriteSectionHeader("Forward Declarations & Identifiers");

        _writer.OpenBlock("typedef enum PspsActorTypeId");
        _writer.WriteLine("ACTOR_TYPE_NONE = 0,");
        foreach (var actor in _symbols.Actors.Values)
        {
            _writer.WriteLine($"ACTOR_TYPE_{actor.Name},");
        }
        _writer.CloseBlock(" PspsActorTypeId;");
        _writer.WriteLine();

        _writer.OpenBlock("typedef enum PspsStateId");
        _writer.WriteLine("STATE_NONE = 0,");
        foreach (var state in _symbols.States.Values)
        {
            _writer.WriteLine($"STATE_{state.Name},");
        }
        _writer.CloseBlock(" PspsStateId;");
        _writer.WriteLine();

        foreach (var st in _symbols.Structs.Values)
        {
            _writer.WriteLine($"typedef struct {st.Name} {st.Name}_t;");
        }

        foreach (var actor in _symbols.Actors.Values)
        {
            _writer.WriteLine($"typedef struct Actor_{actor.Name} Actor_{actor.Name}_t;");
        }

        foreach (var state in _symbols.States.Values)
        {
            _writer.WriteLine($"typedef struct State_{state.Name} State_{state.Name}_t;");
        }

        _writer.WriteLine();
        _writer.WriteLine("static void psps_request_state_transition(PspsStateId next_state);");
        _writer.WriteLine("static void psps_apply_state_transition(void);");

        foreach (var fn in _symbols.Functions.Values.Where(static f => !f.IsBuiltin))
        {
            _writer.WriteLine($"{CTypeMapper.FormatFunctionSignature(null, fn)};");
        }
    }

    // ========================================================================
    // Structs, Assets & Globals
    // ========================================================================

    private void EmitStructsAssetsAndGlobals()
    {
        _writer.WriteSectionHeader("Passive Structs, Baked Assets & Global Variables");

        foreach (var st in _symbols.Structs.Values)
        {
            _writer.OpenBlock($"struct {st.Name}");
            if (st.Fields.Count == 0)
            {
                _writer.WriteLine("uint8_t _unused;");
            }
            else
            {
                foreach (var field in st.Fields.Values)
                {
                    _writer.WriteLine($"{CTypeMapper.FormatFieldDeclaration(field.Type, field.Name)};");
                }
            }
            _writer.CloseBlock(";");
            _writer.WriteLine();
        }

        foreach (var asset in _symbols.Assets.Values)
        {
            _writer.WriteLine($"/* Asset '{asset.Name}' ({asset.AssetKind}: \"{asset.FilePath}\") */");
            _writer.WriteLine($"static psps_texture_t g_asset_{asset.Name};");
            _writer.OpenBlock($"static const uint16_t g_asset_{asset.Name}_pixels[64] =");
            _writer.WriteLine("0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xF8FFu, 0xF8FFu, 0xFFFFu, 0xFFFFu, 0xF8FFu, 0xF8FFu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xF8FFu, 0xF8FFu, 0xFFFFu, 0xFFFFu, 0xF8FFu, 0xF8FFu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xFF8Fu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFF8Fu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xFFFFu, 0xFF8Fu, 0xFF8Fu, 0xFF8Fu, 0xFF8Fu, 0xFFFFu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu,");
            _writer.WriteLine("0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu, 0xFFFFu");
            _writer.CloseBlock(";");
            _writer.WriteLine();
        }

        foreach (var decl in _program.Declarations.OfType<GlobalVarDecl>())
        {
            if (!_symbols.Globals.TryGetValue(decl.Name, out var gSym))
                continue;

            _writer.WriteLine($"/* Scope: {decl.Scope} */");
            _writer.WriteLine($"static {CTypeMapper.FormatFieldDeclaration(gSym.Type, decl.Name)};");
        }

        _writer.WriteLine();
        var rootCtx = new EmissionContext();

        _writer.OpenBlock("static void psps_init_all_globals(void)");
        foreach (var decl in _program.Declarations.OfType<GlobalVarDecl>())
        {
            if (!_symbols.Globals.TryGetValue(decl.Name, out var gSym))
                continue;

            EmitFieldOrVarInitializer(decl.Name, gSym.Type, decl.Initializer, rootCtx);
        }
        _writer.CloseBlock();
        _writer.WriteLine();

        _writer.OpenBlock("static void psps_reset_level_globals(void)");
        foreach (var decl in _program.Declarations.OfType<GlobalVarDecl>())
        {
            if (decl.Scope != MemoryScope.LevelArena || !_symbols.Globals.TryGetValue(decl.Name, out var gSym))
                continue;

            EmitFieldOrVarInitializer(decl.Name, gSym.Type, decl.Initializer, rootCtx);
        }
        _writer.CloseBlock();
    }

    // ========================================================================
    // Message Tagged Union & Frame Mailbox
    // ========================================================================

    private void EmitMessageTaggedUnionAndMailbox()
    {
        _writer.WriteSectionHeader("Message Tagged Union & Static Frame Mailbox");

        _writer.OpenBlock("typedef enum PspsMessageKind");
        _writer.WriteLine("MSG_NONE = 0,");
        foreach (var msg in _symbols.Messages.Values)
        {
            _writer.WriteLine($"MSG_{msg.Name},");
        }
        _writer.CloseBlock(" PspsMessageKind;");
        _writer.WriteLine();

        foreach (var msg in _symbols.Messages.Values)
        {
            _writer.OpenBlock($"typedef struct Msg_{msg.Name}");
            if (msg.Fields.Count == 0)
            {
                _writer.WriteLine("uint8_t _unused;");
            }
            else
            {
                foreach (var field in msg.Fields.Values)
                {
                    _writer.WriteLine($"{CTypeMapper.FormatFieldDeclaration(field.Type, field.Name)};");
                }
            }
            _writer.CloseBlock($" Msg_{msg.Name}_t;");
            _writer.WriteLine();
        }

        _writer.OpenBlock("typedef struct PspsMessage");
        _writer.WriteLine("PspsMessageKind kind;");
        _writer.WriteLine("uint16_t        target_type;");
        _writer.WriteLine("psps_ref_t      target;");
        _writer.OpenBlock("union");
        _writer.WriteLine("uint8_t _raw;");
        foreach (var msg in _symbols.Messages.Values)
        {
            _writer.WriteLine($"Msg_{msg.Name}_t {msg.Name};");
        }
        _writer.CloseBlock(" data;");
        _writer.CloseBlock(" PspsMessage;");
        _writer.WriteLine();

        _writer.WriteLine("static PspsMessage g_mailbox_queue[PSPS_MAILBOX_CAPACITY];");
        _writer.WriteLine("static uint32_t    g_mailbox_count = 0u;");
        _writer.WriteLine();

        _writer.OpenBlock("static inline void psps_enqueue_message(PspsMessage msg)");
        _writer.OpenBlock("if (g_mailbox_count < PSPS_MAILBOX_CAPACITY)");
        _writer.WriteLine("g_mailbox_queue[g_mailbox_count++] = msg;");
        _writer.CloseBlock();
        _writer.CloseBlock();
    }
}
